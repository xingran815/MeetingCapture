#!/usr/bin/env python3
"""Writes the trained neural suppressor (nres.pt) into a Swift source file, so the CLI and the
app carry it without a resource bundle (issue 31). Half precision, base64, in a fixed order
that EchoSuppressor.swift reads back.

  export_nres.py <bench>/nres.pt Sources/MeetingCaptureCore/EchoSuppressorWeights.swift
"""
import base64, hashlib, sys
from pathlib import Path

import numpy as np
import torch

ORDER = [
    "inp.0.weight", "inp.0.bias", "inp.1.weight", "inp.1.bias", "inp.2.weight",
    "gru.weight_ih_l0", "gru.weight_hh_l0", "gru.bias_ih_l0", "gru.bias_hh_l0",
    "gru.weight_ih_l1", "gru.weight_hh_l1", "gru.bias_ih_l1", "gru.bias_hh_l1",
    "out.weight", "out.bias",
]

src, dst = Path(sys.argv[1]), Path(sys.argv[2])
sd = torch.load(src, map_location="cpu")
assert list(sd.keys()) == ORDER, list(sd.keys())
flat = np.concatenate([sd[k].numpy().astype(np.float32).ravel() for k in ORDER])
half = flat.astype("<f2")
print(f"{flat.size} weights, largest half-precision error {np.abs(half.astype(np.float32) - flat).max():.2e}")
blob = base64.b64encode(half.tobytes()).decode()
digest = hashlib.sha256(half.tobytes()).hexdigest()[:16]
lines = [blob[i:i + 100] for i in range(0, len(blob), 100)]
body = "\n".join("        " + l for l in lines)
dst.write_text(f"""// Generated by scripts/aec-bench/export_nres.py from a model trained by nres.py. Don't edit.
// {flat.size} weights, little-endian half precision, sha256 {digest}…, in the order
// EchoSuppressor.NeuralMask reads them.

enum EchoSuppressorWeights {{
    static let count = {flat.size}
    /// Bins the network covers, from 0 Hz up, of the 513 in a 1024-point frame.
    static let bins = {sd["out.bias"].shape[0]}
    /// The GRU's hidden size.
    static let hidden = {sd["gru.weight_hh_l0"].shape[1]}
    static let base64 = \"\"\"
{body}
        \"\"\"
}}
""")
print("wrote", dst, dst.stat().st_size, "bytes")
